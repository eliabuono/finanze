import { chromium } from "playwright";
import http from "node:http"; import fs from "node:fs"; import path from "node:path";
const DIST = path.resolve("dist");
const tipi = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css", ".png": "image/png", ".svg": "image/svg+xml", ".json": "application/json", ".wasm": "application/wasm" };
const srv = http.createServer((q, r) => { let p = decodeURIComponent(new URL(q.url, "http://x").pathname); if (p.endsWith("/")) p += "index.html";
  const f = path.join(DIST, p); if (!fs.existsSync(f)) { r.writeHead(404); r.end(); return; } r.writeHead(200, { "Content-Type": tipi[path.extname(f)] || "application/octet-stream" }); fs.createReadStream(f).pipe(r); }).listen(5181);
const U = "http://localhost:5181/";
const browser = await chromium.launch(); const errori = [];
const ctx = await browser.newContext({ viewport: { width: 1200, height: 900 } });
await ctx.route("https://finanze.elia-buono.workers.dev/**", (r) => r.fulfill({ status: 503, headers: { "Access-Control-Allow-Origin": "*" }, body: "{}" }));
const page = await ctx.newPage(); page.on("pageerror", (e) => errori.push(e.message)); page.on("dialog", (d) => d.accept());
await page.goto(U + "#impostazioni"); await page.waitForSelector("h1");
await page.setInputFiles('input[accept*=".zip"]', fs.readdirSync("ref/dati").map((f) => path.join("ref/dati", f)));
await page.waitForSelector(".avviso.ok");
await page.goto(U + "#importa"); await page.waitForSelector("h1");
await page.setInputFiles('input[accept="application/pdf,.pdf"][multiple]', [process.argv[2]]);
await page.waitForSelector("table.tabella tbody tr", { timeout: 60000 }); await page.waitForTimeout(500);
console.log(await page.locator("table.tabella tbody tr").first().innerText());
await page.goto(U + "#movimenti"); await page.waitForTimeout(500);
const t = await page.locator("body").innerText();
console.log("righe Revolut:", (t.match(/Revolut/g) ?? []).length);
await page.goto(U + "#saldi"); await page.waitForTimeout(600);
console.log("Revolut nei saldi:", (await page.locator("body").innerText()).match(/Revolut[^\n]*\n?[^\n]*/)?.[0]);
console.log("errori:", errori.join("\n") || "nessuno");
await browser.close(); srv.close();
